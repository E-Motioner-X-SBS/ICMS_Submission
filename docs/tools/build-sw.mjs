#!/usr/bin/env node
// Write docs/sw.js: a service worker that precaches the whole site (app, fonts, three.js, the five
// example structures and their precomputed results) so the demo works offline and opens instantly,
// and keeps every structure fetched from RCSB / PDBe for later visits. Also refreshes the preload
// block of index.html (the app's static module graph, and the route's example and chapter).
//
//   node docs/tools/build-sw.mjs      (run after any change to the site; the version is a content hash)
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const DOCS = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// ── index.html: preload the app's static module graph and the route's own files ────────────────
// Without this the browser discovers the modules one import level at a time (six round trips
// before the first chapter on a slow network). The block between the markers is rewritten here.
const { EXAMPLES } = await import(new URL("../js/core/rcsb.js", import.meta.url).href);
const graph = [];
(function visit(rel) {
  if (graph.includes(rel)) return;
  graph.push(rel);
  const src = fs.readFileSync(path.join(DOCS, rel), "utf8");
  for (const m of src.matchAll(/^\s*(?:import|export)\s[^;]*?from\s+["'](\.{1,2}\/[^"']+)["']/gm))
    visit(path.posix.join(path.posix.dirname(rel), m[1]));
})("js/app.js");
const early = `(function () {
  var p = location.hash.replace(/^#\\/?/, "").split("/"), id = null, st = "0000", four = /^[01]{4}$/;
  if (p[0]) { if (four.test(p[0])) st = p[0]; else { try { id = decodeURIComponent(p[0]).toUpperCase(); } catch (e) { return; } st = four.test(p[2] || "") ? p[2] : p.length === 2 && four.test(p[1]) ? p[1] : "0001"; } }
  if (!id && st !== "0000") id = ${JSON.stringify(EXAMPLES[0].id)};
  function link(rel, href, as) { var l = document.createElement("link"); l.rel = rel; l.href = href; if (as) { l.as = as; l.crossOrigin = "anonymous"; } document.head.appendChild(l); }
  if (${JSON.stringify(EXAMPLES.map((e) => e.id))}.indexOf(id) >= 0) link("preload", "data/examples/" + id + ".structure.json", "fetch");
  link("modulepreload", "js/steps/" + st + ".js");
})();`;
const block = [
  "<!-- preload:start (generated by tools/build-sw.mjs) -->",
  ...graph.map((m) => `<link rel="modulepreload" href="${m}">`),
  `<script>${early}</script>`,
  "<!-- preload:end -->",
].join("\n");
const htmlPath = path.join(DOCS, "index.html");
const html = fs.readFileSync(htmlPath, "utf8");
const re = /<!-- preload:start[\s\S]*?<!-- preload:end -->/;
fs.writeFileSync(htmlPath, re.test(html) ? html.replace(re, block) : html.replace('<link rel="stylesheet" href="css/site.css">', `<link rel="stylesheet" href="css/site.css">\n${block}`));
console.log(`index.html: ${graph.length} modules preloaded`);
const SKIP = new Set(["tests", "tools", "sw.js", ".nojekyll"]);
const files = [];
(function walk(dir) {
  for (const f of fs.readdirSync(dir).sort()) {
    const rel = path.relative(DOCS, path.join(dir, f));
    if (SKIP.has(rel.split(path.sep)[0]) || f.startsWith(".")) continue;
    if (/^examples[\\/].*\.cif$/.test(rel)) continue;     // the parsed copies in data/examples/ are what the app loads
    if (fs.statSync(path.join(dir, f)).isDirectory()) walk(path.join(dir, f)); else files.push(rel.split(path.sep).join("/"));
  }
})(DOCS);
const hash = crypto.createHash("sha256");
for (const f of files) { hash.update(f); hash.update(fs.readFileSync(path.join(DOCS, f))); }
const VERSION = hash.digest("hex").slice(0, 12);
const PRECACHE = ["./", ...files.map((f) => `./${f}`)];

const sw = `// GENERATED by tools/build-sw.mjs. Do not edit by hand.
// Precaches the site (version ${VERSION}, ${files.length} files) and keeps RCSB / PDBe structure files.
const VERSION = ${JSON.stringify(VERSION)};
const SHELL = "kmap-shell-" + VERSION, STRUCTURES = "kmap-structures-v1";
const PRECACHE = ${JSON.stringify(PRECACHE, null, 0)};
const STRUCTURE_HOSTS = /^(files\\.rcsb\\.org|models\\.rcsb\\.org|www\\.ebi\\.ac\\.uk)$/;

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith("kmap-shell-") && k !== SHELL).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin === self.location.origin) {
    if (req.mode === "navigate") {              // the page itself, from the same versioned cache as its scripts,
      e.respondWith(caches.open(SHELL).then((c) => c.match(new URL("./", self.location).href)   // so page and modules always match;
        .then((hit) => hit || fetch(req))));    // a new deploy installs a new worker, used from the next load
      return;
    }
    e.respondWith(caches.open(SHELL).then((c) => c.match(req, { ignoreSearch: true })
      .then((hit) => hit || fetch(req).then((r) => { if (r.ok) c.put(req, r.clone()); return r; }))));
    return;
  }
  // deposited structure files do not change: keep them once fetched (search and metadata stay live)
  if (STRUCTURE_HOSTS.test(url.hostname) && /\\.cif|encoding=cif|entry-files/.test(url.href)) {
    e.respondWith(caches.open(STRUCTURES).then((c) => c.match(req)
      .then((hit) => hit || fetch(req).then((r) => { if (r.ok) c.put(req, r.clone()); return r; }))));
  }
});
`;
fs.writeFileSync(path.join(DOCS, "sw.js"), sw);
console.log(`sw.js: version ${VERSION}, ${files.length} files precached`);
