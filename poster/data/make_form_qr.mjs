// QR matrix for the poster's feedback form, written as a module the demo site imports
// (error correction H, so the site's 2 × 2 mark can sit in the centre).
//   node poster/data/make_form_qr.mjs   →  docs/js/core/feedback.js
import QRCode from "qrcode";
import fs from "node:fs";
const FORM = {
  title: "Feedback for Kmap Poster",
  url: "https://forms.gle/TC3bqkSzstSj4hda6",
  embed: "https://docs.google.com/forms/d/e/1FAIpQLSd6H11nEfQbJW_sJHKlii-Nku0CF7bIffsR57Tl-NlDMw5s5Q/viewform?embedded=true",
};
const qr = QRCode.create(FORM.url, { errorCorrectionLevel: "H" });
const n = qr.modules.size, rows = [];
for (let r = 0; r < n; r++) { let s = ""; for (let c = 0; c < n; c++) s += qr.modules.get(r, c) ? "1" : "0"; rows.push(s); }
const out = `// GENERATED by poster/data/make_form_qr.mjs. Do not edit by hand.
// The poster's feedback form: its link, its embeddable address, and a QR code of the link
// (version ${qr.version}, ${n} × ${n} modules, error correction H).
export const FEEDBACK = ${JSON.stringify({ ...FORM, qr: { size: n, rows } }, null, 1)};
`;
fs.writeFileSync(new URL("../../docs/js/core/feedback.js", import.meta.url), out);
console.log(`QR v${qr.version}, ${n}×${n}, ECC H -> ${FORM.url}`);
